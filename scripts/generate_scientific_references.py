#!/usr/bin/env python3
"""Development only: mpmath 200/320 decimal digits, exact binary64 rational inputs."""
import argparse, hashlib, json, math
from pathlib import Path
import mpmath as mp

def exact(x):
    a,b=x.as_integer_ratio()
    return mp.mpf(a)/b

def reference(name,x):
    values=[]
    for precision in (200,320):
        with mp.workdps(precision):values.append(float(getattr(mp,name)(exact(x))))
    if values[0].hex()!=values[1].hex():raise RuntimeError('unstable reference')
    return values[0]

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
    args.output.mkdir(parents=True,exist_ok=True)
    entries=[]
    for name,inputs in [('sin',[.125,-1.25,1e20,1e100]),('cos',[.125,-1.25,1e20,1e100]),('exp',[-.75,.125,3.5,-740.]),('sqrt',[2.,.125,float.fromhex('0x0.0000000000001p-1022')])]:
        for x in inputs:entries.append(dict(operator=name,input=x.hex(),expected=reference(name,x).hex()))
    (args.output/'references.json').write_text(json.dumps(dict(generator='mpmath '+mp.__version__,precision_decimal=[200,320],input_method='binary64 as_integer_ratio',comparison='round to binary64; stability at both precisions',entries=entries),indent=2)+'\n')
    lines=['// Generated by scripts/generate_scientific_references.py; independent mpmath references.','struct ScientificReference { ExpressionKind kind; double input, expected; };','inline constexpr ScientificReference scientificReferences[]{']
    for e in entries:lines.append('    {ExpressionKind::'+e['operator'].capitalize()+', '+e['input']+', '+e['expected']+'},')
    (args.output/'references.hpp').write_text('\n'.join(lines)+'\n};\n')
    for case in ('decay','oscillation','root'):
        if case=='decay':sets=[[k/8 for k in range(33)],[(k+.5)/8 for k in range(32)],[4.25+k/4 for k in range(8)]]
        elif case=='oscillation':sets=[[-4+k/4 for k in range(33)],[-4+(k+.5)/4 for k in range(32)],[-6+k/4 for k in range(8)]+[4.25+k/4 for k in range(8)]]
        else:sets=[[-3+k/4 for k in range(25)],[-3+(k+.5)/4 for k in range(24)],[-5+k/4 for k in range(8)]+[3.25+k/4 for k in range(8)]]
        for label,xs in zip(('training','interior','exterior'),sets):
            rows=['x,y']
            for x in xs:
                ys=[]
                for precision in (200,320):
                    with mp.workdps(precision):
                        z=exact(x)
                        y=mp.exp(-z) if case=='decay' else mp.sin(z)+mp.cos(2*z) if case=='oscillation' else mp.sqrt(1+z*z)
                        ys.append(float(y))
                if ys[0].hex()!=ys[1].hex():raise RuntimeError('unstable target')
                rows.append(format(x,'.17g')+','+format(ys[0],'.17g'))
            (args.output/(case+'-'+label+'.csv')).write_text('\n'.join(rows)+'\n')
    manifest={f.name:hashlib.sha256(f.read_bytes()).hexdigest() for f in sorted(args.output.iterdir()) if f.is_file() and f.name!='SHA256.json'}
    (args.output/'SHA256.json').write_text(json.dumps(manifest,indent=2)+'\n')
if __name__=='__main__':main()
