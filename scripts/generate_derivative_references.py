#!/usr/bin/env python3
"""Development-only analytic derivative references; no runtime dependency."""
import argparse
import json
from pathlib import Path
import mpmath as mp


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    output = parser.parse_args().output
    output.mkdir(parents=True, exist_ok=True)
    entries = []
    for name, inputs in [('sin', [.125, -1.25, 1e20, 1e100]),
                         ('cos', [.125, -1.25, 1e20, 1e100]),
                         ('exp', [-.75, .125, 3.5]), ('log', [.125, 3.5]),
                         ('sqrt', [.125, 2.])]:
        for x in inputs:
            rounded = []
            for precision in (200, 320):
                with mp.workdps(precision):
                    a, b = x.as_integer_ratio()
                    z = mp.mpf(a) / b
                    y = {'sin': lambda: mp.cos(z), 'cos': lambda: -mp.sin(z),
                         'exp': lambda: mp.exp(z), 'log': lambda: 1 / z,
                         'sqrt': lambda: 1 / (2 * mp.sqrt(z))}[name]()
                    rounded.append(float(y).hex())
            if rounded[0] != rounded[1]:
                raise RuntimeError('unstable reference')
            entries.append(dict(operator=name, input=x.hex(), expected=rounded[0]))
    (output / 'references.json').write_text(json.dumps(dict(
        generator='mpmath ' + mp.__version__, precision_decimal=[200, 320],
        input_method='exact binary64 as_integer_ratio',
        method='analytic first derivative, independently rounded; stability at both precisions',
        entries=entries), indent=2) + '\n')
    lines = ['// Generated by scripts/generate_derivative_references.py.',
             'struct DerivativeReference { ExpressionKind kind; double input, expected; };',
             'inline constexpr DerivativeReference derivativeReferences[]{']
    for e in entries:
        lines.append('    {ExpressionKind::' + e['operator'].capitalize() + ', ' +
                     e['input'] + ', ' + e['expected'] + '},')
    (output / 'references.hpp').write_text('\n'.join(lines) + '\n};\n')


if __name__ == '__main__':
    main()
